import fs from 'fs';
import path from 'path';

console.log('Running post-build mobile & performance optimization...');

// Verify that dist/index.html exists and contains rich content and AdSense verification
const indexPath = path.resolve('dist/index.html');
if (fs.existsSync(indexPath)) {
  const content = fs.readFileSync(indexPath, 'utf8');
  if (!content.includes('ca-pub-6643535431949281')) {
    console.warn('Warning: AdSense account verification tag missing from dist/index.html. Injecting...');
    const updated = content.replace('</head>', '  <meta name="google-adsense-account" content="ca-pub-6643535431949281" />\n</head>');
    fs.writeFileSync(indexPath, updated, 'utf8');
  }
  console.log(`✓ Verified dist/index.html (${content.length} bytes, preserved rich multilingual hub)`);
} else {
  console.error('Error: dist/index.html was not generated by Astro build!');
}
