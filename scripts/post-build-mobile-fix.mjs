import fs from 'fs';
import path from 'path';

console.log('Running post-build mobile & performance optimization...');

// Verify that dist/index.html exists and contains rich content and AdSense verification
const indexPath = path.resolve('dist/index.html');
if (fs.existsSync(indexPath)) {
  const content = fs.readFileSync(indexPath, 'utf8');
  if (!content.includes('ca-pub-6643535431949281')) {
    console.warn('Warning: AdSense account verification tag missing from dist/index.html. Injecting...');
    const updated = content.replace('</head>', '  <meta name="google-adsense-account" content="ca-pub-6643535431949281" />\n</head>');
    fs.writeFileSync(indexPath, updated, 'utf8');
  }
  console.log(`✓ Verified dist/index.html (${content.length} bytes, preserved rich multilingual hub)`);
} else {
  console.error('Error: dist/index.html was not generated by Astro build!');
}

// Ensure all HTML files have properly escaped ampersands in Google Fonts and link attributes
function sanitizeHtmlEntitiesInDist(dir) {
  if (!fs.existsSync(dir)) return;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      sanitizeHtmlEntitiesInDist(full);
    } else if (entry.name.endsWith('.html')) {
      let content = fs.readFileSync(full, 'utf8');
      let modified = false;

      // Fix bare ampersands in Google Fonts URL queries (resolves 4x HTML structure errors)
      if (content.includes('fonts.googleapis.com') && (content.includes('&family=') || content.includes('&display='))) {
        content = content
          .replace(/&family=/g, '&amp;family=')
          .replace(/&display=/g, '&amp;display=');
        modified = true;
      }

      if (modified) {
        fs.writeFileSync(full, content, 'utf8');
      }
    }
  }
}

sanitizeHtmlEntitiesInDist(path.resolve('dist'));
console.log('✓ Verified HTML attribute entity encoding across all built pages');
